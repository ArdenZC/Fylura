/** U4 real Chromium interactions with deterministic browser mock data. Not native acceptance. */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright";
import { createServer } from "vite";
import { assertCheckoutEvidence } from "./ciEvidence.mjs";
const actualCheckoutSha = execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const actualCheckoutTree = execFileSync("git", ["rev-parse", "HEAD^{tree}"], { encoding: "utf8" }).trim();
const sourceHead = process.env.U4_SOURCE_HEAD ?? actualCheckoutSha;
const expectedCheckoutSha = process.env.U4_EXPECTED_CHECKOUT_SHA;
if (expectedCheckoutSha) assertCheckoutEvidence(expectedCheckoutSha, actualCheckoutSha);
const output = path.resolve(process.env.U4_OUTPUT_DIR ?? ".tmp-tests/u4-browser");
await mkdir(output, { recursive: true });
const server = await createServer({ server: { host: "127.0.0.1", port: 0, strictPort: false } });
await server.listen();
const baseUrl = server.resolvedUrls?.local?.[0]?.replace(/\/$/u, "");
if (!baseUrl) throw new Error("U4 browser gate: Vite did not expose a local URL.");
const browser = await chromium.launch({ headless: true });
const checks = [], errors = [];
let page;
try {
  page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.addInitScript(() => { Object.defineProperty(navigator, "platform", { get: () => "Win32" }); localStorage.setItem("zc-onboarding-complete", "true"); localStorage.setItem("zc-language", "en"); });
  await page.goto(`${baseUrl}/?browser-mock=1`);
  await page.getByRole("button", { name: "Files", exact: true }).click();
  assert.equal(await page.title(), "Zen Canvas");
  const pane = page.locator('[role="tabpanel"]:not([hidden]) [data-pane-id]').first();
  await pane.getByRole("button", { name: "View all indexed files", exact: true }).click();
  const row = pane.locator('[role="option"]').first();
  await row.click();
  await pane.locator('[data-file-library-context-toggle]').click();
  const editor = page.locator('[data-u4-personal]');
  const libraryContext = page.locator('[data-file-library-context-content]');
  assert.equal(await libraryContext.getByRole('button', { name: 'Quick preview', exact: true }).count(), 1);
  assert.equal(await libraryContext.getByRole('button', { name: 'Show in folder', exact: true }).count(), 1);
  assert.equal(await libraryContext.getByRole('button', { name: 'Previous selected item', exact: true }).count(), 0);
  assert.equal(await libraryContext.getByRole('button', { name: 'Next selected item', exact: true }).count(), 0);
  checks.push("Library Inspector shares one Quick Preview and Reveal entry; single selection hides inactive previous/next controls");
  await editor.getByRole("textbox", { name: "File notes", exact: true }).fill("U4 project handoff — keep the review notes with this managed file.");
  await editor.getByRole("button", { name: "Save note", exact: true }).click();
  await editor.getByRole("button", { name: "Favorite file", exact: true }).click();
  await editor.getByRole("button", { name: "Unfavorite file", exact: true }).waitFor();
  checks.push("Managed note and favorite saved from Inspector");
  await page.screenshot({ path: path.join(output, "01-inspector-wide-light.png") });
  await page.locator('.file-library-context-panel-content').evaluate((element) => { element.scrollTop = 0; });
  await page.screenshot({ path: path.join(output, "00-inspector-metadata-wide-light.png") });
  await pane.getByRole("button", { name: "Notes and file favorites", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.locator("li button").first().waitFor();
  await page.screenshot({ path: path.join(output, "02-favorites-wide-light.png") });
  await page.evaluate(() => document.documentElement.classList.add("dark"));
  await page.screenshot({ path: path.join(output, "13-favorites-wide-dark.png") });
  await page.evaluate(() => document.documentElement.classList.remove("dark"));
  await dialog.getByRole("button", { name: "Files with notes", exact: true }).click();
  await dialog.locator("li button").first().click();
  await editor.getByRole("textbox", { name: "File notes", exact: true }).waitFor();
  assert.match(await editor.getByRole("textbox").inputValue(), /U4 project handoff/);
  checks.push("Notes and favorites return to canonical Inspector without replacing query/sort");
  await page.reload();
  await page.getByRole("button", { name: "Files", exact: true }).click();
  await pane.getByRole("button", { name: "Notes and file favorites", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.locator("li button").first().click();
  assert.match(await editor.getByRole("textbox").inputValue(), /U4 project handoff/);
  checks.push("Mock metadata survives page reload; native SQLite restart covered separately");
  await page.evaluate(() => document.documentElement.classList.add("dark"));
  await page.screenshot({ path: path.join(output, "03-inspector-wide-dark.png") });
  await page.locator('[data-file-library-context-content]').getByRole('button', { name: 'Quick preview', exact: true }).first().click();
  await page.locator('[data-preview-host="zen-floating"]').waitFor();
  await page.screenshot({ path: path.join(output, "04-preview-wide-dark.png") });
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 820, height: 800 });
  // Compact presentation uses the existing modal SideSheet.
  await pane.locator('[data-file-library-context-toggle]').click();
  await editor.getByRole("textbox").waitFor();
  await page.screenshot({ path: path.join(output, "05-inspector-compact-dark.png") });
  await page.evaluate(() => document.documentElement.classList.remove("dark"));
  await page.screenshot({ path: path.join(output, "06-inspector-compact-light.png") });
  await page.locator('[data-file-library-context-content]').getByRole('button', { name: 'Quick preview', exact: true }).first().click();
  await page.locator('[data-preview-host="zen-floating"]').waitFor();
  await page.screenshot({ path: path.join(output, "09-preview-compact-light.png") });
  await page.evaluate(() => document.documentElement.classList.add("dark"));
  await page.screenshot({ path: path.join(output, "10-preview-compact-dark.png") });
  await page.keyboard.press("Escape");
  assert.equal(await pane.locator('[data-file-library-context-toggle]').evaluate((element) => document.activeElement === element), true);
  await page.evaluate(() => document.documentElement.classList.remove("dark"));
  assert.equal(await page.evaluate(() => document.body.scrollWidth <= innerWidth), true);
  await pane.getByRole("button", { name: "Notes and file favorites", exact: true }).click();
  await page.getByRole("dialog").locator("li button").first().waitFor();
  await page.screenshot({ path: path.join(output, "14-favorites-compact-light.png") });
  await page.evaluate(() => document.documentElement.classList.add("dark"));
  await page.screenshot({ path: path.join(output, "15-favorites-compact-dark.png") });
  await page.keyboard.press("Escape");
  await page.evaluate(() => document.documentElement.classList.remove("dark"));
  checks.push("Compact light/dark Inspector, favorites, Quick Preview, Escape and no horizontal overflow");
  await page.setViewportSize({ width: 1600, height: 1000 });
  await pane.getByRole("button", { name: "Edit path (Ctrl/Cmd+L)", exact: true }).click();
  await pane.getByRole("textbox", { name: "Folder path", exact: true }).fill("C:/U3/Left");
  await pane.getByRole("textbox", { name: "Folder path", exact: true }).press("Enter");
  const browseRows = pane.locator('[data-browse-entry-kind]');
  await browseRows.nth(1).click();
  await browseRows.nth(2).click({ modifiers: ["ControlOrMeta"] });
  await pane.locator('[data-file-library-context-toggle]').click();
  await pane.getByText("Temporary Browse item:", { exact: false }).waitFor();
  await page.screenshot({ path: path.join(output, "07-browse-selection-light.png") });
  assert.equal(await pane.locator('[data-u4-personal]').count(), 0);
  const before = await pane.locator('[aria-selected="true"]').count();
  await pane.getByRole("button", { name: "Next selected item", exact: true }).click();
  await page.locator('[data-preview-host="zen-floating"]').waitFor();
  assert.equal(await pane.locator('[aria-selected="true"]').count(), before);
  await page.screenshot({ path: path.join(output, "08-browse-preview-light.png") });
  await page.locator('[data-preview-navigation="previous"]').click();
  assert.equal(await page.locator('[data-preview-navigation="next"]').isEnabled(), true);
  assert.equal(await pane.locator('[aria-selected="true"]').count(), before);
  checks.push("Browse multi-selection preview and shared-host Previous/Next preserve selection; no durable metadata editor");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Dual pane", exact: true }).click();
  const right = page.locator('[role="tabpanel"]:not([hidden]) [data-pane-id]').nth(1);
  await right.getByRole("button", { name: "Edit path (Ctrl/Cmd+L)", exact: true }).click();
  await right.getByRole("textbox", { name: "Folder path", exact: true }).fill("C:/U3/Right");
  await right.getByRole("textbox", { name: "Folder path", exact: true }).press("Enter");
  await right.locator('[data-browse-entry-kind]').nth(1).click();
  const leftSelection = await pane.locator('[aria-selected="true"]').count();
  await right.locator('[data-file-library-context-toggle]').click();
  await page.getByText("Temporary Browse item:", { exact: false }).waitFor();
  const rightInspector = right.locator('[data-file-library-context-panel]');
  assert.equal(await rightInspector.getAttribute('data-file-library-context-layout'), 'pane-overlay');
  assert.equal(await rightInspector.evaluate((element) => getComputedStyle(element).position), 'absolute');
  assert.equal(await page.locator('[aria-modal="true"]').count(), 0);
  const overlayWithinPane = await rightInspector.evaluate((element) => {
    const paneElement = element.closest('[data-pane-id]');
    if (!paneElement) return false;
    const panel = element.getBoundingClientRect();
    const paneRect = paneElement.getBoundingClientRect();
    return panel.left >= paneRect.left && panel.right <= paneRect.right && panel.top >= paneRect.top && panel.bottom <= paneRect.bottom;
  });
  assert.equal(overlayWithinPane, true);
  checks.push("Wide dual-pane Inspector overlays only its owning pane and does not dim or block the peer pane");
  await page.screenshot({ path: path.join(output, "11-dual-pane-inspector-light.png") });
  await page.locator('[data-file-library-context-content]').getByRole('button', { name: 'Quick preview', exact: true }).first().click();
  await page.locator('[data-preview-host="zen-floating"]').waitFor();
  await page.keyboard.press("Escape");
  assert.equal(await pane.locator('[aria-selected="true"]').count(), leftSelection);
  assert.equal(await right.locator('[data-file-library-context-toggle]').evaluate((element) => document.activeElement === element), true);
  checks.push("Dual-pane Inspector preview and Escape return to owning pane; peer selection retained");
  for (const width of [820, 980, 1440, 1600]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.body.scrollWidth <= innerWidth), true, `page overflow at ${width}px`);
    if (width >= 1440) {
      await right.locator('[data-file-library-context-toggle]').click();
      await rightInspector.waitFor();
      assert.equal(await rightInspector.getAttribute('data-file-library-context-layout'), 'pane-overlay');
      await page.screenshot({ path: path.join(output, `16-dual-inspector-${width}.png`) });
      await right.locator('[data-file-library-context-toggle]').click();
    }
  }
  checks.push("820/980/1440/1600 layouts have no horizontal page overflow; wide dual-pane Inspector remains pane-scoped");
  // Chinese layout is an independent browser-mock page, not a native-platform claim.
  const chinese = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  await chinese.addInitScript(() => { Object.defineProperty(navigator, "platform", { get: () => "Win32" }); localStorage.setItem("zc-onboarding-complete", "true"); localStorage.setItem("zc-language", "zh"); });
  await chinese.goto(`${baseUrl}/?browser-mock=1`);
  await chinese.getByRole("button", { name: "文件", exact: true }).click();
  const zhPane = chinese.locator('[role="tabpanel"]:not([hidden]) [data-pane-id]').first();
  const allFiles = zhPane.getByRole("button", { name: "查看所有已索引文件", exact: true });
  if (await allFiles.count()) await allFiles.click();
  await zhPane.getByRole("button", { name: "笔记与文件收藏", exact: true }).click();
  await chinese.getByRole("dialog").getByRole("button", { name: "文件收藏", exact: true }).waitFor();
  await chinese.evaluate(() => document.documentElement.classList.add("dark"));
  await chinese.screenshot({ path: path.join(output, "12-chinese-favorites-dark.png") });
  await chinese.close();
  checks.push("Chinese empty favorites and dark layout");
  await right.locator('[data-file-library-context-toggle]').click();
  await page.locator('[data-file-library-context-content]').getByRole('button', { name: 'Show in folder', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Cannot show this item in the system file manager.' }).waitFor();
  assert.equal(await right.locator('[data-u4-personal]').count(), 0);
  checks.push("Browse Reveal uses the live ephemeral ref and shows an honest unavailable state in browser mock; OS GUI remains native acceptance");
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, "checks.json"), JSON.stringify({ sourceHead, head: actualCheckoutSha, tree: actualCheckoutTree, evidence: "Real Chromium / deterministic browser mock; no native GUI or actual filesystem Restore claim", url: page.url(), checks, errors }, null, 2));
  console.log(JSON.stringify({ output, checks, errors }, null, 2));
} catch (error) { if (page) { await writeFile(path.join(output, "failure.txt"), await page.locator("body").innerText()); await page.screenshot({ path: path.join(output, "failure.png") }); } console.error(error); throw error; }
finally { await browser.close(); await server.close(); }
